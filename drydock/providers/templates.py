"""Code templates: render pipeline.py / dag.py / mapping.yaml from an IngestionPlan.

The rendered code is what the harness executes in a sandbox and what a reviewer opens
first, so it is plain, commented, standard-library-only Python (LLD section 3). The same
module also hosts ``inject_defect``, which turns clean output into one of the six frozen
corpus defects (LLD section 2.2) by a targeted, plausible edit.
"""

from __future__ import annotations

import json
import re
from string import Template
from typing import Any

import yaml
from pydantic import BaseModel, ConfigDict, ValidationError

from drydock.models import CANONICAL_COLUMNS, ColumnSpec, IngestionPlan, SourceFormat
from drydock.providers import ProviderError

DEFECT_IDS: frozenset[str] = frozenset(
    {
        "date_format_swapped",
        "trailer_not_skipped",
        "wrong_slice",
        "amount_sign_dropped",
        "thousands_separator_kept",
        "dag_missing_dependency",
    }
)

FILE_EXTENSION: dict[SourceFormat, str] = {
    SourceFormat.CSV: "csv",
    SourceFormat.FIXED_WIDTH: "txt",
    SourceFormat.JSON_LINES: "jsonl",
}

_THOUSANDS_MARKER = 'cleaned.replace(",", "")'
MAX_LINE_LENGTH = 100  # generated code follows the repository's ruff line length


class ParseOptions(BaseModel):
    """Typed view of ``IngestionPlan.parse_options`` with the LLD defaults."""

    model_config = ConfigDict(frozen=True, extra="ignore")

    delimiter: str = ","
    encoding: str = "utf-8"
    header_rows: int = 1
    trailer_rows: int = 0
    skip_blank_lines: bool = True


def parse_options(plan: IngestionPlan) -> ParseOptions:
    try:
        return ParseOptions.model_validate(plan.parse_options)
    except ValidationError as exc:
        raise ProviderError(f"plan.parse_options is invalid: {exc}") from exc


def _py(value: Any) -> str:
    """Render a Python literal for a str / int / bool / None value."""
    if value is None:
        return "None"
    if isinstance(value, bool):
        return "True" if value else "False"
    if isinstance(value, int):
        return str(value)
    return json.dumps(str(value))


