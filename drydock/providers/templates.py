_DAG_TEMPLATE = Template(
    '''"""Airflow DAG for ${client} / ${feed_name}: extract -> transform -> load.

Generated by DRYDOCK. Imports are limited to the Airflow DAG and PythonOperator classes,
datetime and the sibling pipeline module. Rows move between tasks through XCom.
"""

from datetime import datetime

from airflow import DAG
from airflow.operators.python import PythonOperator

import pipeline

# Airflow renders {{ ds }} to the logical date, so each run reads that day's drop.
SOURCE_PATH = ${source_path}


def _extract(path):
    """Task 1: read the raw feed; the rows travel to the next task via XCom."""
    return pipeline.extract(path)


def _transform(ti):
    """Task 2: map raw rows onto the canonical schema."""
    rows = ti.xcom_pull(task_ids=${extract_id})
    return pipeline.transform(rows)


def _load(ti):
    """Task 3: hand canonical rows to the sink."""
    rows = ti.xcom_pull(task_ids=${transform_id})
    return pipeline.load(rows)


with DAG(
    dag_id=${dag_id},
    schedule=${schedule},
    start_date=datetime(2026, 1, 1),
    catchup=False,
) as dag:
    extract = PythonOperator(
        task_id=${extract_id},
        python_callable=_extract,
        op_kwargs={"path": SOURCE_PATH},
    )
    transform = PythonOperator(task_id=${transform_id}, python_callable=_transform)
    load = PythonOperator(task_id=${load_id}, python_callable=_load)

    extract >> transform >> load
'''
)


def render_dag(plan: IngestionPlan) -> str:
    """Render dag.py: three PythonOperators chained extract >> transform >> load."""
    if len(plan.task_ids) != 3:
        raise ProviderError(f"plan.task_ids must name exactly three tasks, got {plan.task_ids}")
    extract_id, transform_id, load_id = plan.task_ids
    extension = FILE_EXTENSION[plan.format]
    source_path = f"/data/inbound/{plan.client}/{plan.feed_name}/{{{{ ds }}}}.{extension}"
    return _DAG_TEMPLATE.substitute(
        client=plan.client,
        feed_name=plan.feed_name,
        source_path=_py(source_path),
        dag_id=_py(f"{plan.client}__{plan.feed_name}"),
        schedule=_py(plan.schedule_cron),
        extract_id=_py(extract_id),
        transform_id=_py(transform_id),
        load_id=_py(load_id),
    )


