def _describe_transform(column: ColumnSpec) -> str | None:
    """Human-readable transform note for the mapping document, or None when it is a copy."""
    steps: list[str] = []
    if column.dtype == "date":
        steps.append(f"strptime({column.date_format or '%Y-%m-%d'!r}) -> YYYY-MM-DD")
    if column.dtype == "decimal":
        steps.append("strip thousands separator; Decimal quantized to 2 dp")
        if column.sign_column:
            steps.append(f"negative when {column.sign_column} == {column.negative_marker!r}")
    if column.dtype == "int":
        steps.append("int()")
    if column.target == "currency":
        steps.append("upper()")
    if column.default is not None:
        steps.append(f"default {column.default!r} when empty")
    return "; ".join(steps) or None


def render_mapping(plan: IngestionPlan) -> str:
    """Render the Harbormaster-compatible mapping.yaml (client, feed, format, fields)."""
    fields: list[dict[str, Any]] = []
    for column in plan.column_map:
        field: dict[str, Any] = {
            "source": column.source,
            "target": column.target,
            "dtype": column.dtype,
        }
        note = _describe_transform(column)
        if note is not None:
            field["transform"] = note
        fields.append(field)
    document = {
        "client": plan.client,
        "feed": plan.feed_name,
        "format": plan.format.value,
        "fields": fields,
    }
    return str(yaml.safe_dump(document, sort_keys=False, allow_unicode=True))


def render_all(plan: IngestionPlan) -> tuple[str, str, str]:
    """Convenience: (pipeline_py, dag_py, mapping_yaml) for one plan."""
    return render_pipeline(plan), render_dag(plan), render_mapping(plan)


# --------------------------------------------------------------------------- #
# Defect injection (LLD section 2.2)                                           #
# --------------------------------------------------------------------------- #


def _swap_day_month(fmt: str) -> str:
    """Swap %d and %m ("%d/%m/%Y" <-> "%m/%d/%Y"): the classic transatlantic date bug."""
    return fmt.replace("%d", "\x00").replace("%m", "%d").replace("\x00", "%m")


def _defect_date_format_swapped(pipeline_py: str) -> str:
    match = re.search(r'date_format="([^"]*)"', pipeline_py)
    if match is None or not ("%d" in match.group(1) or "%m" in match.group(1)):
        return pipeline_py
    swapped = _swap_day_month(match.group(1))
    return pipeline_py[: match.start(1)] + swapped + pipeline_py[match.end(1) :]


def _defect_trailer_not_skipped(pipeline_py: str) -> str:
    # Reads as "nobody noticed the totals footer": the trailer count is simply zero.
    pattern = r"^TRAILER_ROWS = [1-9]\d*"
    return re.sub(pattern, "TRAILER_ROWS = 0", pipeline_py, count=1, flags=re.M)


def _defect_wrong_slice(pipeline_py: str) -> str:
    # Off-by-one in the layout: the currency slice starts one character too early, so the
    # last digit of the amount bleeds into the currency code ("0US" instead of "USD").
    match = re.search(r'source="(\d+):(\d+)", target="currency"', pipeline_py) or re.search(
        r'source="(\d+):(\d+)"', pipeline_py
    )
    if match is None:
        return pipeline_py
    start, end = int(match.group(1)) - 1, int(match.group(2)) - 1
    suffix = ', target="currency"' if 'target="currency"' in match.group(0) else ""
    shifted = f'source="{start}:{end}"{suffix}'
    return pipeline_py[: match.start()] + shifted + pipeline_py[match.end() :]


def _defect_amount_sign_dropped(pipeline_py: str) -> str:
    # The DR/CR flag is mapped but never consulted, so every amount comes out positive.
    return re.sub(r'sign_column="[^"]*"', "sign_column=None", pipeline_py, count=1)


def _defect_thousands_separator_kept(pipeline_py: str) -> str:
    # The separator-stripping line is missing, so "1,234.50" reaches Decimal() as-is.
    lines = pipeline_py.split("\n")
    kept = [line for line in lines if _THOUSANDS_MARKER not in line]
    return "\n".join(kept) if len(kept) == len(lines) - 1 else pipeline_py


def _defect_dag_missing_dependency(dag_py: str) -> str:
    # The DAG author chained the first two tasks and forgot the third.
    pattern = r"^([ \t]*)(\w+) >> (\w+) >> (\w+)[ \t]*$"
    return re.sub(pattern, r"\1\2 >> \3", dag_py, count=1, flags=re.M)


_PIPELINE_DEFECTS = {
    "date_format_swapped": _defect_date_format_swapped,
    "trailer_not_skipped": _defect_trailer_not_skipped,
    "wrong_slice": _defect_wrong_slice,
    "amount_sign_dropped": _defect_amount_sign_dropped,
    "thousands_separator_kept": _defect_thousands_separator_kept,
}


def inject_defect(pipeline_py: str, dag_py: str, defect_id: str) -> tuple[str, str]:
    """Apply one frozen defect id to rendered code; returns new (pipeline_py, dag_py).

    Raises ``ProviderError`` for an unknown id, or when the artifact has nothing the defect
    could plausibly break (e.g. ``wrong_slice`` on a CSV feed) so scenarios never pass by
    accident.
    """
    if defect_id not in DEFECT_IDS:
        raise ProviderError(f"unknown defect id '{defect_id}'; known: {sorted(DEFECT_IDS)}")
    if defect_id == "dag_missing_dependency":
        new_dag = _defect_dag_missing_dependency(dag_py)
        if new_dag == dag_py:
            raise ProviderError("defect 'dag_missing_dependency' is not applicable: no chain")
        return pipeline_py, new_dag
    new_pipeline = _PIPELINE_DEFECTS[defect_id](pipeline_py)
    if new_pipeline == pipeline_py:
        raise ProviderError(f"defect '{defect_id}' is not applicable to this pipeline")
    return new_pipeline, dag_py
